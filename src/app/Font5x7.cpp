const u8* glyph(char c) {
    const unsigned char uc = static_cast<unsigned char>(c);
    if (uc < 32 || uc > 126) return kGlyphs[0];   // fuera de rango -> espacio
    return kGlyphs[uc - 32];
}

const u8* glyphUnicode(u32 cp) {
    if (cp >= 32 && cp <= 126) return kGlyphs[cp - 32];
    for (int i = 0; i < kLatinCount; ++i)
        if (kLatinCodes[i] == cp) return kLatinGlyphs[i];
    return nullptr;
}

u32 nextUtf8(const char*& p) {
    if (!p || !*p) return 0;
    const unsigned char c0 = static_cast<unsigned char>(*p);

    // Secuencias de 1 a 4 bytes. Una continuacion invalida se trata como
    // fin de caracter para no quedarse leyendo basura indefinidamente.
    if (c0 < 0x80) { ++p; return c0; }

    auto cont = [](const char* q) -> bool {
        return (static_cast<unsigned char>(*q) & 0xC0) == 0x80;
    };

    if ((c0 & 0xE0) == 0xC0 && cont(p + 1)) {
        const u32 cp = ((c0 & 0x1Fu) << 6) |
                        (static_cast<unsigned char>(p[1]) & 0x3Fu);
        p += 2; return cp;
    }
    if ((c0 & 0xF0) == 0xE0 && cont(p + 1) && cont(p + 2)) {
        const u32 cp = ((c0 & 0x0Fu) << 12) |
                       ((static_cast<unsigned char>(p[1]) & 0x3Fu) << 6) |
                        (static_cast<unsigned char>(p[2]) & 0x3Fu);
        p += 3; return cp;
    }
    if ((c0 & 0xF8) == 0xF0 && cont(p + 1) && cont(p + 2) && cont(p + 3)) {
        const u32 cp = ((c0 & 0x07u) << 18) |
                       ((static_cast<unsigned char>(p[1]) & 0x3Fu) << 12) |
                       ((static_cast<unsigned char>(p[2]) & 0x3Fu) << 6) |
                        (static_cast<unsigned char>(p[3]) & 0x3Fu);
        p += 4; return cp;
    }

    ++p;              // byte suelto invalido: saltarlo
    return 0xFFFD;    // caracter de reemplazo
}

size_t lengthUtf8(const char* utf8) {
    if (!utf8) return 0;
    size_t n = 0;
    for (const char* p = utf8; nextUtf8(p); ) ++n;
    return n;
}

i32 measureUtf8(const char* utf8, i32 scale) {
    if (!utf8 || scale <= 0) return 0;
    const i32 n = static_cast<i32>(lengthUtf8(utf8));
    if (n == 0) return 0;
    return (n * kGlyphW + (n - 1)) * scale;
}

void drawTextUtf8(Framebuffer& fb, i32 x, i32 y, const char* utf8, Color color, i32 scale) {
    if (!utf8 || scale <= 0) return;

    i32 penX = x;
    for (const char* p = utf8; *p; ) {
        const u32 cp = nextUtf8(p);
        if (cp == 0) break;
        if (cp == '\n') { penX = x; y += (kGlyphH + 2) * scale; continue; }

        // Sin glifo se dibuja un espacio: mejor un hueco que un simbolo raro.
        const u8* g = glyphUnicode(cp);
        if (g) {
            for (i32 col = 0; col < kGlyphW; ++col) {
                const u8 bits = g[col];
                if (!bits) continue;
                for (i32 row = 0; row < kGlyphH; ++row) {
                    if (!(bits & (1u << row))) continue;
                    if (scale == 1)
                        fb.blendPixel(penX + col, y + row, color);
                    else
                        fb.fillRect({penX + col * scale, y + row * scale, scale, scale}, color);
                }
            }
        }
        penX += (kGlyphW + 1) * scale;
    }
}

i32 measure(const char* text, i32 scale) {
    if (!text || scale <= 0) return 0;
    i32 n = 0;
    for (const char* p = text; *p; ++p) ++n;
    if (n == 0) return 0;
    // n glifos de 5 px + (n-1) separaciones de 1 px, todo por escala.
    return (n * kGlyphW + (n - 1)) * scale;
}

void drawText(Framebuffer& fb, i32 x, i32 y, const char* text, Color color, i32 scale) {
    if (!text || scale <= 0) return;

    i32 penX = x;
    for (const char* p = text; *p; ++p) {
        if (*p == '\n') { penX = x; y += (kGlyphH + 2) * scale; continue; }

        const u8* g = glyph(*p);
        for (i32 col = 0; col < kGlyphW; ++col) {
            const u8 bits = g[col];
            if (!bits) continue;
            for (i32 row = 0; row < kGlyphH; ++row) {
                if (!(bits & (1u << row))) continue;
                if (scale == 1)
                    fb.blendPixel(penX + col, y + row, color);
                else
                    fb.fillRect({penX + col * scale, y + row * scale, scale, scale}, color);
            }
        }
        penX += (kGlyphW + 1) * scale;
    }
}

